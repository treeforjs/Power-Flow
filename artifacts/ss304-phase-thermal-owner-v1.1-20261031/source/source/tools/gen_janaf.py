#!/usr/bin/python -I
"""Transcribe the NIST-JANAF gas and liquid tables of Fe, Cr and Ni into source/janaf_data.h.

The numeric fields are copied as text (no reformatting), so the header holds exactly the published digits.
Usage: gen_janaf.py DATA_DIR OUT_HEADER
"""
import hashlib, sys
from pathlib import Path

TABLES = [('fe_gas', 'Fe-008'), ('fe_liquid', 'Fe-006'), ('cr_gas', 'Cr-005'), ('cr_liquid', 'Cr-003'),
          ('ni_gas', 'Ni-005'), ('ni_liquid', 'Ni-003'), ('mn_gas', 'Mn-005'), ('mn_liquid', 'Mn-003'),
          ('si_gas', 'Si-005'), ('si_liquid', 'Si-003'), ('c_gas', 'C-003'), ('c_graphite', 'C-002')]


def rows(path):
    out, dfh = [], None
    for line in path.read_text().splitlines()[2:]:
        p = line.split()
        if len(p) < 5:
            continue
        try:
            [float(x) for x in p[:5]]
        except ValueError:
            continue
        T = p[0]
        if out and float(out[-1][0]) == float(T):
            # Transition rows repeat T with equal S and H (a Cp step at a glass/liquid transition): keep the upper side.
            if (out[-1][2], out[-1][4]) != (p[2], p[4]):
                raise SystemExit('duplicate temperature with different S or H in ' + path.name)
            out[-1] = p[:5]
            continue
        out.append(p[:5])
        if float(T) == 298.15:
            dfh = p[5]
    if dfh is None:
        raise SystemExit('no 298.15 K row in ' + path.name)
    return out, dfh


def main():
    data, out = Path(sys.argv[1]), Path(sys.argv[2])
    text = ['// Generated by tools/gen_janaf.py from the NIST-JANAF tables listed below (Chase 1998, J. Phys. Chem. Ref.',
            '// Data Monograph 9; https://janaf.nist.gov/tables/<ID>.txt). Columns copied as text: T (K), Cp (J/mol/K),',
            '// S (J/mol/K), H-H(298.15) (kJ/mol). Do not edit by hand.',
            '#pragma once', 'namespace ss304_phase_v1_1 { namespace janaf {',
            'struct Row { double T, Cp, S, HmH298; };',
            'struct Table { const char* id; const char* sha256; double dfH298_kJ_mol; int n; const Row* rows; };']
    tables = []
    for name, tid in TABLES:
        path = data / (tid + '.txt')
        digest = hashlib.sha256(path.read_bytes()).hexdigest()
        r, dfh = rows(path)
        text.append('inline constexpr Row %s_rows[] = {' % name)
        for p in r:
            text.append('    {%s, %s, %s, %s},' % (p[0], p[1], p[2], p[4]))
        text.append('};')
        tables.append('inline constexpr Table %s = {"%s", "%s", %s, %d, %s_rows};' % (name, tid, digest, dfh, len(r), name))
    text += tables + ['}} // namespace ss304_phase_v1_1::janaf', '']
    out.write_text('\n'.join(text))


if __name__ == '__main__':
    main()
