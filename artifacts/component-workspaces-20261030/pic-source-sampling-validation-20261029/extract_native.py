#!/usr/bin/env python3
"""Extract unchanged native source into a CPU-only source sampler; record each slice."""
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
FROZEN = Path('/home/treefor/projects/runtimes/mfem-gpu-pic-20261029/source')
OUT = Path('<workspace>/outputs/pic-profile/source-sampling-validation')
cpp = FROZEN / 'src/mfem_gap_pic.cpp'
header = FROZEN / 'include/raikou/mfem_gap_pic.h'
driver = FROZEN / 'examples/mfem_heating_history_pic.cpp'
pieces = []

def take(path, start, end):
    data = path.read_bytes()
    a = data.index(start.encode())
    b = data.index(end.encode(), a)
    block = data[a:b]
    pieces.append(dict(path=str(path), start_line=data[:a].count(b'\n')+1,
                       end_line=data[:b].count(b'\n')+1, bytes=len(block),
                       sha256=hashlib.sha256(block).hexdigest(), verbatim=True))
    return block.decode()

types = take(header, 'inline constexpr double pic_e', '// Relativistic Boris momentum update.')
helpers = take(cpp, 'constexpr double kb', 'PicVector cross(')
check = take(cpp, 'void check_particle(', '\n}\n\nvoid pic_parallel_workers')
energy = take(cpp, 'double pic_kinetic_energy_J(', '\nPicVector pic_boris(')
emission = take(cpp, 'void GapPic::inject_thermal_electrons(', '\nvoid GapPic::set_external_fields(')
thermal = take(driver, 'struct Thermal {', '\nstruct Fields {')
reservoir = take(driver, 'struct Reservoir {', '\nvoid snapshot(')
accumulate = take(driver, '            bool injected=false;', '\n            if(!injected && pic.particles().empty())')

prefix = '''// Generated by extract_native.py. Native slices are byte-for-byte unchanged.
#pragma once
#include <algorithm>
#include <array>
#include <cmath>
#include <cstdint>
#include <filesystem>
#include <fstream>
#include <limits>
#include <numeric>
#include <random>
#include <stdexcept>
#include <string>
#include <vector>
namespace raikou::mfem_backend {
'''
shim = '''
// Storage-only host: no MFEM object, MPI, fields, trajectory, or GPU dependency.
// Every value read/written by the native emission methods has its native type.
class GapPic {
public:
    GapPicOptions options_;
    std::vector<GapParticle> particles_;
    GapPicDiagnostics ledger_;
    bool fields_current_ = false;
    std::uint64_t next_particle_id_ = 1;
    explicit GapPic(GapPicOptions o): options_(o) {}
    void inject_thermal_electrons(GapElectrode,double,double,double,int,std::uint64_t,GapSurface,double,double);
    void inject_surface_profile(GapElectrode,GapSurface,const std::vector<double>&,const std::vector<double>&,double,int,std::uint64_t);
};
double pic_kinetic_energy_J(const GapParticle&);
'''
result = prefix+types+helpers+shim+check+'\n'+energy+emission+'\n}\nusing namespace raikou::mfem_backend;\n'+thermal+reservoir+'''
template<class Capture>
void accumulate_native(Capture& pic,std::array<Reservoir,4>& reservoir,
    std::array<std::vector<double>,4>& T,double dt,const GapPicOptions& o,
    const Thermal& thermal,std::uint64_t step) {
'''+accumulate+'\n(void)injected; (void)thermal;\n}\n'
target = ROOT / 'native_slice.hpp'
target.write_text(result)
# Verify each recorded byte block is present unchanged in generated output.
for piece in pieces:
    data = Path(piece['path']).read_bytes().splitlines(keepends=True)
    block = b''.join(data[piece['start_line']-1:piece['end_line']-1])
    # Some endpoints occur within a line; use the recorded byte count.
    block = b''.join(data[piece['start_line']-1:])[:piece['bytes']]
    assert hashlib.sha256(block).hexdigest() == piece['sha256']
    assert block in target.read_bytes()
manifest = dict(method='verbatim native routines with a storage-only host class',
    no_math_reimplementation=True, no_mfem_mpi_cuda_linkage=True,
    slices=pieces, generated_sha256=hashlib.sha256(target.read_bytes()).hexdigest(),
    frozen_sha256={str(p):hashlib.sha256(p.read_bytes()).hexdigest() for p in [cpp, header, driver]})
inputs = [Path('<workspace>/outputs/heating-history-full.bin')]
audit = Path('<workspace>/outputs/pic-profile/particle-audit')
inputs += [audit/'audit-report.txt', audit/'inventory.json', audit/'copied-checkpoint/restart.meta', audit/'copied-checkpoint/checkpoint_400040.bin']
manifest['inputs_sha256_before'] = {str(p):hashlib.sha256(p.read_bytes()).hexdigest() for p in inputs}
(OUT/'native-equivalence.json').write_text(json.dumps(manifest,indent=2)+'\n')
print('Verified',len(pieces),'unchanged native slices')
